package com.example.backend.service.impl;

import com.example.backend.dto.Response;
import com.example.backend.dto.RoomDTO;
import com.example.backend.entity.Room;
import com.example.backend.exeption.OurException;
import com.example.backend.repo.BookingRepository;
import com.example.backend.repo.RoomRepository;
import com.example.backend.service.AwsS3Service;
import com.example.backend.service.interfac.IRoomService;
import com.example.backend.utils.Utils;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.data.domain.Sort;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;

import java.io.File;
